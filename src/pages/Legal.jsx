// **טקסט** → מודגש. עדיף על dangerouslySetInnerHTML בשביל הדגשה בודדת.
function withBold(text) {
  return text.split(/\*\*(.+?)\*\*/g).map((part, i) =>
    i % 2 ? <strong key={i} style={{ color: "#fff" }}>{part}</strong> : part);
}

