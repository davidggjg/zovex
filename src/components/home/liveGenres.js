// category אחת ויחידה, "שידורים חיים", ואין שום שדה genre/group. כלומר אין
// מה לקרוא, ולכן הסיווג נגזר מהשם. זה לא אידיאלי, אבל זו האפשרות היחידה
// בלי לגעת בצד השרת, והשמות אצלך עקביים מספיק כדי שזה יעבוד.
//
// הסדר קובע: הכלל הראשון שמתאים מנצח. ילדים לפני סרטים כדי ש-"yes Movies
// Kids" ילך לילדים ולא לסרטים; סדרות לפני לייף־סטייל כדי ש-"HOT סדרות" לא
// ייבלע ע"י כלל ה-HOT הכללי.

const RULES = [
  ["👶 ילדים", [
    /ילדים/, /בייבי/, /ג'וניור/, /גוניור/, /ניקולודיון/, /טין ניק/, /ניק /,
    /דיסני/, /דסני/, /קידס/, /kids/i, /לולי/, /הופ/, /חינוכית/, /הכוכבים/, /wiz/i,
  ]],
  ["⚽ ספורט", [/ספורט/, /יורוספורט/, /ufc/i, /\bone\b/i]],
  ["📰 חדשות ואקטואליה", [
    /חדשות/, /כאן\s*11/, /מכאן/, /רשת\s*13/, /ראשת\s*13/, /i24/i, /\bc14\b/i,
    /mako/i, /הכנסת/, /ערוץ\s*24/, /ערוץ\s*98/, /^ערוץ\s*9$/,
  ]],
  ["🌍 דוקו וטבע", [/דוקו/, /נשיונל/, /היסטוריה/, /דיסקברי/, /discovery/i, /geographic/i]],
  ["🎬 סרטים", [
    /cinema/i, /movies/i, /קולנוע/, /סרטים/, /gold/i, /אימה/, /רומנטיקה/, /bollywood/i,
  ]],
  ["📺 סדרות ודרמה", [
    /דרמות/, /דרמה/, /drama/i, /סדרות/, /comedy/i, /קומדיה/, /hbo/i,
    /טלנובלות/, /ויוה/, /action/i, /בית\+/, /yes\s*ישראלי/i,
  ]],
  ["✨ לייף סטייל ובידור", [
    /אוכל/, /food/i, /health/i, /לייף/, /בידור/, /ריל/, /real/i, /זום/, /זון/,
    /קריוקי/, /חיים טובים/, /ים תיכוני/, /e!/i, /משפחה/, /free\s*tv/i, /hot\s*\d/i,
  ]],
];

const OTHER = "📡 עוד ערוצים";

export function genreOf(title) {
  const t = String(title || "");
  for (const [name, patterns] of RULES) {
    if (patterns.some(re => re.test(t))) return name;
  }
  return OTHER;
}

/** מקבל רשימת ערוצים ומחזיר [{title, items}] לפי סדר הז'אנרים שלמעלה. */
export function groupLiveByGenre(channels) {
  const buckets = new Map();
  for (const ch of channels) {
    const g = genreOf(ch.title);
    if (!buckets.has(g)) buckets.set(g, []);
    buckets.get(g).push(ch);
  }
  // סדר קבוע לפי RULES, ו"עוד ערוצים" תמיד אחרון — אחרת סדר השורות משתנה
  // בכל טעינה לפי סדר ההגעה של הערוצים, וזה מבלבל מי שרגיל למקום שלהן.
  const order = [...RULES.map(([n]) => n), OTHER];
  return order
    .filter(n => buckets.has(n))
    .map(n => ({ title: n, items: buckets.get(n) }));
}
