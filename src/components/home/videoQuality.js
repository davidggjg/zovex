// ─────────────────────────────────────────────────────────────────────────────
// בחירת הווריאנט הטוב ביותר בזרם HLS/DASH.
//
// Shaka ללא הגדרת ABR מתחיל בהערכת רוחב פס נמוכה, בוחר וריאנט נמוך
// ומטפס. בזרם עם 1080p הצופה רואה איכות נמוכה בשניות הראשונות,
// ולפעמים נשאר שם. לכן בוחרים במפורש.
//
// הפונקציה הוצאה לכאן כדי שאפשר יהיה לבדוק אותה: הגרסה הראשונה
// שכתבתי הייתה
//
//     tracks.reduce((a, b) => (bH - aH) || (bBw - aBw) > 0 ? b : a)
//
// וזה בוחר את הווריאנט ה**נמוך**: הפרש הגבהים הוא מספר, וכל מספר
// שאינו אפס הוא truthy — גם שלילי. כלומר התנאי היה "יש הפרש גבהים"
// ולא "b גבוה יותר".
// ─────────────────────────────────────────────────────────────────────────────
export function bestVariant(tracks) {
  if (!Array.isArray(tracks) || !tracks.length) return null;
  // גובה קודם, ואז קצב סיביות — שני וריאנטים באותו גובה נבדלים
  // באיכות הקידוד. וריאנט בלי גובה (אודיו בלבד) נדחה לסוף.
  return tracks.reduce((best, t) => {
    const bh = best.height || 0;
    const th = t.height || 0;
    if (th !== bh) return th > bh ? t : best;
    return (t.bandwidth || 0) > (best.bandwidth || 0) ? t : best;
  });
}
